import AppKit
import Foundation
import UniformTypeIdentifiers

final class ClipboardMonitor: ClipboardMonitoring {
    var onNewItem: ((ClipboardCapture) -> Void)?

    // Markers from the nspasteboard.org convention that clipboard managers must respect.
    static let ignoredPasteboardTypes: Set<NSPasteboard.PasteboardType> = [
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")
    ]

    private let pollInterval: TimeInterval
    private let pasteboard: NSPasteboard
    private let ignoredApps: IgnoredAppsProviding
    private let frontmostApp: FrontmostAppProviding
    private var timer: Timer?
    private var lastChangeCount: Int

    init(
        pollInterval: TimeInterval = 0.5,
        pasteboard: NSPasteboard = .general,
        ignoredApps: IgnoredAppsProviding = UserDefaultsIgnoredApps(),
        frontmostApp: FrontmostAppProviding = WorkspaceFrontmostApp()
    ) {
        self.pollInterval = pollInterval
        self.pasteboard = pasteboard
        self.ignoredApps = ignoredApps
        self.frontmostApp = frontmostApp
        self.lastChangeCount = pasteboard.changeCount
    }

    deinit { stopMonitoring() }

    func startMonitoring() {
        stopMonitoring()
        timer = Timer.scheduledTimer(withTimeInterval: pollInterval, repeats: true) { [weak self] _ in
            self?.checkForClipboardChanges()
        }
    }

    func stopMonitoring() {
        timer?.invalidate()
        timer = nil
    }

    func checkForClipboardChanges() {
        let current = pasteboard.changeCount
        guard current != lastChangeCount else { return }
        lastChangeCount = current

        let types = Set(pasteboard.types ?? [])
        guard types.isDisjoint(with: Self.ignoredPasteboardTypes) else {
            AppLogger.monitor.debug("Skipped pasteboard item marked as concealed, transient or auto-generated")
            return
        }

        // shortcut: polling every 0.5 s means a quick app switch can report the wrong source app;
        // upgrade to an event-based source if that becomes a problem.
        if let bundleID = frontmostApp.frontmostBundleIdentifier, ignoredApps.isIgnored(bundleIdentifier: bundleID) {
            AppLogger.monitor.debug("Skipped pasteboard item copied from ignored app \(bundleID, privacy: .public)")
            return
        }

        if let imageCapture = makeImageCapture() {
            onNewItem?(imageCapture)
            return
        }

        guard let string = pasteboard.string(forType: .string) else { return }
        let trimmed = string.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !trimmed.isEmpty else { return }
        onNewItem?(.text(string))
    }

    private func makeImageCapture() -> ClipboardCapture? {
        let preferredTypes: [NSPasteboard.PasteboardType] = [.png, .tiff]
        let otherImageTypes = (pasteboard.types ?? []).filter { type in
            !preferredTypes.contains(type) && UTType(type.rawValue)?.conforms(to: .image) == true
        }

        for type in preferredTypes + otherImageTypes {
            if let data = pasteboard.data(forType: type), !data.isEmpty {
                guard data.count <= ImageFileStore.maxItemBytes else {
                    AppLogger.monitor.warning("Skipped image larger than the 10 MB item limit")
                    return nil
                }
                return .image(data: data, pasteboardType: type.rawValue)
            }
        }
        return nil
    }
}
